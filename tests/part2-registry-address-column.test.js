// PART 2. 등기부 표에서 주소에 옆 칸 글자가 붙지 않게 하기 (실제 양식 서류 점검, 값은 모두 가짜)
// - 대지권 표: "1. 서울특별시 중구 가상동 주차장 812㎡ …" → 지목("주차장", "대")은 주소가 아니다
// - 1동 표제부 [도로명주소]: "… 가상로 활주택), 판매시설," → 옆 건물내역 칸("…도시형생활주택), 판매시설,")은 주소가 아니다
import { describe, it, expect } from 'vitest';
import { findAddresses } from '../src/features/document-analysis/name-detector.js';

const values = (/** @type {string} */ text) => findAddresses(text).map((a) => a.value);

describe('PART 2 대지권 표: 주소 뒤의 지목은 주소가 아니다', () => {
  it.each([
    ['1 1. 서울특별시 중구 가상동 주차장 812㎡ 2020년1월2일 등기', '서울특별시 중구 가상동'],
    ['2 2. 서울특별시 중구 가상동1가 대 345㎡ 2021년3월4일 토지 지목변경', '서울특별시 중구 가상동1가'],
    ['1 1. 서울특별시 강북구 가상동 대 1234.5㎡ 2022년5월6일 등기', '서울특별시 강북구 가상동'],
    ['1 1. 서울특별시 중구 가상동 123-4 잡종지 56.7㎡', '서울특별시 중구 가상동 123-4'],
  ])('%s', (line, expected) => {
    expect(values(line)).toEqual([expected]);
  });

  it('면적이 바로 오지 않는 "대"·"도로"는 끊지 않는다 (주소 속 낱말일 수 있다)', () => {
    expect(values('서울특별시 중구 가상대로 12')).toEqual(['서울특별시 중구 가상대로 12']);
    expect(values('서울특별시 중구 가상동 대 가상빌딩')).toEqual(['서울특별시 중구 가상동 대 가상빌딩']);
  });
});

describe('PART 2 1동 표제부 [도로명주소]: 옆 건물내역 칸 글자는 주소가 아니다', () => {
  it('짝 없는 닫는 괄호가 있는 낱말(옆 칸 글자)에서 끊는다', () => {
    expect(values('[도로명주소] 서울특별시 강북구 가상로 활주택), 판매시설,')).toEqual(['서울특별시 강북구 가상로']);
    expect(values('서울특별시 중구 가상로 12 근린생활시설) 3층')).toEqual(['서울특별시 중구 가상로 12']);
  });

  it('건물 용도 이름("판매시설", "제2종근린생활시설") 뒤가 쉼표·줄 끝이면 끊는다', () => {
    expect(values('[도로명주소] 서울특별시 강북구 가상로 34 판매시설, 업무시설')).toEqual(['서울특별시 강북구 가상로 34']);
    expect(values('서울특별시 강북구 가상로 34 제2종근린생활시설')).toEqual(['서울특별시 강북구 가상로 34']);
  });

  it.each([
    '서울특별시 중구 가상로 12 가상시설 301호',
    '서울특별시 중구 가상동 123 공공시설 2층',
    '서울특별시 중구 가상로 12 판매시설 2층',
  ])('건물 이름이 "…시설"인 주소는 끝까지 잡는다: %s (PR #245 리뷰)', (line) => {
    expect(values(line)).toEqual([line]);
  });

  it('주소 뒤 괄호(동 이름·건물 이름)는 지금처럼 주소에 넣는다', () => {
    expect(values('서울특별시 중구 가상로 12, 3층 (가상동, 가상타운) 301호')).toEqual([
      '서울특별시 중구 가상로 12, 3층 (가상동, 가상타운) 301호',
    ]);
  });
});
